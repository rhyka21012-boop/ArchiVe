/// 再生位置 (「続きから見る」) の判定を 2 つのプレイヤーで共有するための定義。
///
/// 保存は GlobalPlayerLayer と LocalVideoPlayerPage の両方が行い、
/// どちらも同じ prefs キー (`offline_pos_<url>`) を使う。判定が片方だけ
/// ずれると「ウィジェットには出るのに再生すると先頭から始まる」といった
/// 食い違いになるため、しきい値はここに一本化する。
library;

/// 「ほぼ見終わった」と見なす残り秒数のしきい値。
///
/// 以前は固定 10 秒だったが、それでは 10 秒未満の動画は再生位置 0 秒でも
/// `残り < 10` が成立してしまい、中断位置が必ず消されていた。結果として
/// 短い動画は「続きから見る」に一度も載らなかった。
/// 動画の長さに対する割合 (5%) で見ることでこれを解消する。
///
/// 上限を 10 秒に据えているのは長い動画の挙動を変えないため。
/// 割合だけで見ると 1 時間の動画で「残り 3 分」が見終わり扱いになってしまう。
/// 200 秒 (= 10 / 0.05) 以上の動画は従来どおり 10 秒で判定される。
double nearEndThresholdSec(int durSec) {
  final ratio = durSec * 0.05;
  return ratio < 10 ? ratio : 10;
}

/// 再生位置が動画の終端付近かどうか。
///
/// 終端付近なら中断位置を残さず (次回は先頭から)、復元もしない。
/// 長さが取得できていない (0 以下) 場合は判定しない。
bool isNearEnd(int durSec, int posSec) =>
    durSec > 0 && durSec - posSec < nearEndThresholdSec(durSec);
